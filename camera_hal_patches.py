def apply_camera_hal_patch(sites, ctx, file, file_path, *args, **kwargs):
    with open(file_path, 'rb+') as f:
        data = bytearray(f.read())
        for offset, stock, patched in sites:
            current = int.from_bytes(data[offset:offset + 4], 'little')
            if current != stock:
                raise ValueError(f'{file_path}: {offset:#x} is {current:#010x}, expected {stock:#010x}')
            data[offset:offset + 4] = patched.to_bytes(4, 'little')
        f.seek(0)
        f.write(data)
