# 1080p60 recording on the main camera (S5KJN1), as instruction patches of the stock
# MediaTek camera HAL: (file offset, stock instruction, patched instruction). The sensor has a
# 1080p60 mode and the encoder keeps up, but the HAL advertised 30 fps only and switched to a
# 60 fps sensor mode (HFPS) only on an MTK vendor session key.
# - libcam.halsensor.so / libmtkcam.logicalmodule.so: COMMON_CONTROL_AE_COMMON advertises
#   15-60 and 60-60 fps. The front (S5K4H7) and mono (GC02M1B) PLATFORM_MODULE functions
#   build their own 10-30 fps ranges in place of their availableSceneModes entry (uint8 ->
#   int32 pushes) and skip their sceneModeOverrides, so both scene keys fall back to the
#   COMMON_TUNING defaults (DISABLED / [1, 1, 0]).
# - libmtkcam_metastore.so: 16.7 ms min frame duration for the mid-size streams (one register
#   shared by all of them; sizes above 1080p also claim it, the HAL then stays at 30 fps);
#   aeTargetFpsRange becomes a session key in place of prerelease (imagereaderid is added
#   again at runtime).
# - libmtkcam_pipelinepolicy.so: HFPS when the session aeTargetFpsRange starts at 60 (was the
#   MTK key 0x80080002 == 1).
# The S5KJN1 driver votes the top MMDVFS step in that mode (kernel); 1080p records at 56-60 fps.

